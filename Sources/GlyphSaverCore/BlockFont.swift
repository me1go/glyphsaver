/// Built-in ANSI-Shadow-style block font so plain text ("LEAP CRM") renders as
/// big terminal block art without external FIGlet tools. Letters are uppercased;
/// unsupported characters render as '?'. 6 rows per glyph.
public enum BlockFont {
    /// True when the string is plain text to render through the font
    /// (single line); multi-line input is treated as ready-made ASCII art.
    public static func isPlainText(_ text: String) -> Bool {
        !text.contains("\n")
    }

    /// Render plain text into block art. Multi-line input is returned as-is.
    public static func render(_ text: String) -> AsciiArt {
        guard isPlainText(text) else { return AsciiArt(text: text) }
        var rows = [String](repeating: "", count: glyphHeight)
        for ch in text.uppercased() {
            let glyph = glyphs[ch] ?? (ch == " " ? space : glyphs["?"]!)
            for r in 0..<glyphHeight {
                rows[r] += glyph[r] + " "
            }
        }
        return AsciiArt(text: rows.joined(separator: "\n"))
    }

